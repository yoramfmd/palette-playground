import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';

const inputPath = path.resolve('research/data/huemint/website-magazine.jsonl');
const outputPath = path.resolve('app/js/huemint-corpus.js');

const records = (await readFile(inputPath, 'utf8'))
  .split(/\r?\n/)
  .filter(Boolean)
  .map(line => JSON.parse(line))
  .map(({ id, colors, score, generator, creativity, preset, template, source }) => ({
    id,
    colors,
    score,
    generator,
    creativity,
    preset,
    template,
    source
  }));

await mkdir(path.dirname(outputPath), { recursive: true });
await writeFile(
  outputPath,
  `// Generated by npm run huemint:browser-corpus. Do not edit by hand.\nwindow.HUEMINT_LOCAL_CORPUS = ${JSON.stringify(records, null, 2)};\n`,
  'utf8'
);

console.log(`Wrote ${records.length} real Huemint palettes to ${outputPath}`);
