import { mkdir, readFile, readdir, writeFile } from 'node:fs/promises';
import path from 'node:path';

const dataDirectory = path.resolve('research/data/huemint');
const inputPaths = (await readdir(dataDirectory))
  .filter(name => name.endsWith('.jsonl'))
  .sort()
  .map(name => path.join(dataDirectory, name));
const outputPath = path.resolve('app/js/huemint-corpus.js');
const catalog = JSON.parse(await readFile(path.join(dataDirectory, 'templates.json'), 'utf8'));

const sources = await Promise.all(inputPaths.map(async inputPath => {
  try {
    return await readFile(inputPath, 'utf8');
  } catch (error) {
    if (error.code === 'ENOENT') return '';
    throw error;
  }
}));

const records = sources.flatMap(source => source.split(/\r?\n/).filter(Boolean).map(line => JSON.parse(line)))
  .map(({ id, colors, score, generator, creativity, preset, template, source }) => ({
    id,
    colors,
    score,
    generator,
    creativity,
    preset,
    template,
    source
  }));

await mkdir(path.dirname(outputPath), { recursive: true });
await writeFile(
  outputPath,
  `// Generated by npm run huemint:browser-corpus. Do not edit by hand.\nwindow.HUEMINT_TEMPLATE_CATALOG = ${JSON.stringify(catalog.map(({ category, slug, label, numColors }) => ({ category, slug, label, numColors })), null, 2)};\nwindow.HUEMINT_LOCAL_CORPUS = ${JSON.stringify(records, null, 2)};\n`,
  'utf8'
);

console.log(`Wrote ${records.length} real Huemint palettes to ${outputPath}`);
